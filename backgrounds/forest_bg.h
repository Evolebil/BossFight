/**
 * @file forest_bg.h
 * @brief Процедурные фоны меню — лес (главное меню) и башня (выбор уровня).
 *        Рисуются напрямую примитивами SDL (без PNG), поэтому не требуют
 *        ассетов и масштабируются под любое разрешение.
 * @author evol
 * @date 2026-02-20
 */
#pragma once
#include "../config/common.h"

// ============================================================
// ПРИМИТИВЫ
// ============================================================

/**
 * @brief Контур окружности — обход по углам точками (не алгоритм Брезенхема,
 *        для фона такой точности достаточно).
 */
void drawCircleOutline(SDL_Renderer* renderer, int centerX, int centerY, int radius);

/**
 * @brief Закрашенная окружность построчным сканированием.
 */
void drawCircleFilled(SDL_Renderer* renderer, int centerX, int centerY, int radius);

/**
 * @brief Закрашенный треугольник: сортирует вершины по Y и линейно
 *        интерполирует левую/правую границу построчно.
 */
void drawTriangleFilled(SDL_Renderer* renderer, int x1, int y1, int x2, int y2, int x3, int y3);

// ============================================================
// ФОНЫ СЦЕН
// ============================================================

/**
 * @brief Фон главного меню — лес, дальние горы со снежными шапками,
 *        центральная гора с башней, холмы, деревья.
 * @param brightness Множитель яркости (0..1, из Config). Применяется только
 *        к небу и дальним горам — так было в изначальной реализации,
 *        остальные элементы яркость не учитывают.
 */
void drawForestBackground(SDL_Renderer* renderer, float brightness);

/**
 * @brief Фон экрана выбора уровня — башня на градиентном небе.
 * @param brightness Не используется этой функцией — параметр оставлен
 *        только для единой сигнатуры с drawForestBackground.
 */
void drawTowerBackground(SDL_Renderer* renderer, float brightness);